import cv2
import numpy as np
from typing import Dict, Tuple

# Basic tools: Mask / Boundary / Uniform format

def ensure_binary_mask(x: np.ndarray, thr: int = 127) -> np.ndarray:
    """
    Unify all output formats into a binary mask of uint8 (0 / 255).
    """
    if x.ndim == 3:
        x = cv2.cvtColor(x, cv2.COLOR_RGB2GRAY)
    if x.dtype != np.uint8:
        x = x.astype(np.float32)
        if x.max() <= 1.0:
            x = x * 255.0
        x = np.clip(x, 0, 255).astype(np.uint8)
    _, m = cv2.threshold(x, thr, 255, cv2.THRESH_BINARY)
    return m

def boundary_from_mask(mask01_or_255: np.ndarray) -> np.ndarray:
    """
    Convert segmentation masks to boundary maps (0/255).
    """
    m = mask01_or_255.copy()
    if m.dtype != np.uint8:
        m = m.astype(np.uint8)
    if m.max() == 1:
        m = (m * 255).astype(np.uint8)
    m = cv2.threshold(m, 127, 255, cv2.THRESH_BINARY)[1]
    kernel = np.ones((3, 3), np.uint8)
    er = cv2.erode(m, kernel, 1)
    bd = cv2.subtract(m, er)
    return bd  # 0 / 255

# Four methods of output

def mask_from_contour_method(masked_from_file: np.ndarray) -> np.ndarray:
    # ContourDetection.apply The target mask has been returned (0/255 or 0/1)
    return ensure_binary_mask(masked_from_file)

def mask_from_otsu(thresh_from_file: np.ndarray) -> np.ndarray:
    # OtsuThresholding.apply return thresh(0/255)
    return ensure_binary_mask(thresh_from_file)

def _pick_best_mask_by_contour_similarity(
    img_rgb: np.ndarray, candidates, tol: int = 2
) -> Tuple[np.ndarray, float]:
    """
    Select one mask from multiple candidate clusters.
    This is solely employed to select a target region from multiple clusters generated by k-means.
    """
    gray = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2GRAY)
    if tol > 0:
        gray = cv2.GaussianBlur(gray, (2 * tol + 1, 2 * tol + 1), 0)
    edge_ref = cv2.Canny(gray, 80, 160)  # 0/255

    def boundary_f1(edge_pre, edge_post, tol_pix=2):
        a = (edge_pre > 0).astype(np.uint8)   # reference
        b = (edge_post > 0).astype(np.uint8)  # predicted
        if a.sum() == 0 or b.sum() == 0:
            return 0.0, 0.0, 0.0
        k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * tol_pix + 1, 2 * tol_pix + 1))
        a_d = cv2.dilate(a, k, 1)
        b_d = cv2.dilate(b, k, 1)
        prec = (b & a_d).sum() / (b.sum() + 1e-9)
        rec = (a & b_d).sum() / (a.sum() + 1e-9)
        f1 = 2 * prec * rec / (prec + rec + 1e-9)
        return float(prec), float(rec), float(f1)

    best = None
    best_score = -1.0
    for m in candidates:
        bd = boundary_from_mask(m)
        _, _, f1 = boundary_f1(edge_ref, bd, tol_pix=tol)
        if f1 > best_score:
            best_score = f1
            best = m
    return best, best_score


def mask_from_kmeans(img_rgb: np.ndarray, segmented_rgb: np.ndarray) -> np.ndarray:
    """
    Convert the colour-coded K-means clustering results into a single-object binary mask.

    Strategy:
    - Calculate the average brightness for each cluster within the segmented RGB image segmented_rgb
    - Designate the ‘darkest cluster’ as the background
    - Treat all other clusters as foreground and integrate them into a single foreground mask
    """
    # segmented_rgb is the output of KMeans_Clustering (each cluster assigned a fixed colour)
    h, w, _ = segmented_rgb.shape
    seg = segmented_rgb.reshape(-1, 3)

    # Find all distinct colours (corresponding to each cluster)
    colors, inv = np.unique(seg, axis=0, return_inverse=True)  # colors[K,3], inv[N]

    # Calculate the average brightness for each cluster
    # Using simple greyscale: Y = 0.299 R + 0.587 G + 0.114 B
    brightness = (0.299 * colors[:, 0] +
                  0.587 * colors[:, 1] +
                  0.114 * colors[:, 2])

    # The cluster deemed the darkest is the background.
    bg_idx = int(np.argmin(brightness))

    # Foreground = All clusters that are not background
    inv_2d = inv.reshape(h, w)
    fg01 = (inv_2d != bg_idx).astype(np.uint8)   # 0/1

    # Return 0/255 mask
    return (fg01 * 255).astype(np.uint8)

def mask_from_watershed(markers: np.ndarray) -> np.ndarray:
    """
    WatershedSegmentation.apply return markers:
      -1: Watershed line
       1: Background
      >1: Foreground
    Merge all foreground elements into a single target.
    """
    return ((markers > 1).astype(np.uint8) * 255)


# Boundary Evaluation (Single GT Mask)

def _boundary_recall_bsds(
    pb: np.ndarray,
    gt_mask: np.ndarray,
    nthresh: int = 30,
    max_dist_frac: float = 0.0075,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    TP = pred ∧ GT
    FN = ¬pred ∧ GT
    R = TP / (TP + FN)

    pb: Probability map of the forecast outlook, range [0,1] or [0,255]
    gt_mask: GT mask (0/255 or 0/1)
    """
    # Normalise to [0,1]
    pb = pb.astype(np.float32)
    if pb.max() > 1.0:
        pb = pb / 255.0

    # GT Outlook (0/1)
    gt_fg = (ensure_binary_mask(gt_mask) > 0).astype(np.uint8)

    # Maintain the same threshold scanning style as before
    if nthresh <= 1:
        thresh = np.array([0.5], dtype=np.float32)
    else:
        thresh = np.linspace(
            1.0 / (nthresh + 1),
            1.0 - 1.0 / (nthresh + 1),
            nthresh,
        ).astype(np.float32)

    R_list = []

    for t in thresh:
        # Obtain the predicted probability (0/1) based on the threshold
        pred_fg = (pb >= t).astype(np.uint8)

        # The extreme case is analogous to the original logic, except that only Recall is retained.
        if pred_fg.sum() == 0 and gt_fg.sum() == 0:
            # Neither side holds promise; treat as R=1.
            R_list.append(1.0)
            continue
        if pred_fg.sum() == 0 or gt_fg.sum() == 0:
            # If only one side has prospects, then R=0
            R_list.append(0.0)
            continue

        # Regional Edition TP / FN
        pred_bool = pred_fg > 0
        gt_bool = gt_fg > 0

        TP = np.logical_and(pred_bool, gt_bool).sum()
        FN = np.logical_and(np.logical_not(pred_bool), gt_bool).sum()

        R = TP / (TP + FN + 1e-9)
        R_list.append(float(R))

    return thresh, np.array(R_list, dtype=np.float32)


def evaluate_methods_bsds(
    img_rgb: np.ndarray,
    outputs_dict: Dict[str, np.ndarray],
    gt_mask: np.ndarray,
    nthresh: int = 30,
    max_dist_frac: float = 0.0075,
):
    """
    outputs_dict:
      {
        "contour":   contour_mask_or_pb,
        "otsu":      otsu_mask,
        "kmeans":    segmented_rgb,
        "watershed": markers
      }

    gt_mask: GT mask (0/1 or 0/255), foreground = target area.
    Return:
      scores: {method: {"Rmax", "T"}}   # Method Recall: Maximum value and corresponding threshold
      rec_curves: {method: np.ndarray [N,2] -> [thresh, R]}
      masks: Binary mask used for evaluation (visualisation optional)
    """
    gt_mask_bin = ensure_binary_mask(gt_mask)

    masks: Dict[str, np.ndarray] = {}
    pbs: Dict[str, np.ndarray] = {}

    # 1) First consolidate the four methods into a binary mask.
    masks["contour"] = mask_from_contour_method(outputs_dict["contour"])
    masks["otsu"] = mask_from_otsu(outputs_dict["otsu"])
    masks["kmeans"] = mask_from_kmeans(img_rgb, outputs_dict["kmeans"])
    masks["watershed"] = mask_from_watershed(outputs_dict["watershed"])

    # 2) From mask to foreground; “Probability map”(pb)
    #    Here, the mask/255 is directly used as pb (0 or 1).
    for name, m in masks.items():
        pbs[name] = ensure_binary_mask(m).astype(np.float32) / 255.0

    scores: Dict[str, Dict[str, float]] = {}
    rec_curves: Dict[str, np.ndarray] = {}

    # 3) Evaluate each method based solely on recall.
    for name, pb in pbs.items():
        thresh, R = _boundary_recall_bsds(
            pb,
            gt_mask_bin,
            nthresh=nthresh,
            max_dist_frac=max_dist_frac,
        )
        # Select only the point with the highest recall
        idx = int(np.argmax(R))
        bestR = float(R[idx])
        T = float(thresh[idx])

        scores[name] = {
            "Rmax": bestR,
            "T": T,
        }

    return masks, scores
